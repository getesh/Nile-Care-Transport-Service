package com.NEMT.Niel.Care.Transportation.model;

public class ContactForm {
	
	 	private String formName;
	    private String formPhone;
	    private String formEmail;
	    private String formMessage;
	    
	    
		
		public ContactForm() {
			
		}
		public String getFormName() {
			return formName;
		}
		public void setFormName(String formName) {
			this.formName = formName;
		}
		public String getFormPhone() {
			return formPhone;
		}
		public void setFormPhone(String formPhone) {
			this.formPhone = formPhone;
		}
		public String getFormEmail() {
			return formEmail;
		}
		public void setFormEmail(String formEmail) {
			this.formEmail = formEmail;
		}
		public String getFormMessage() {
			return formMessage;
		}
		public void setFormMessage(String formMessage) {
			this.formMessage = formMessage;
		}
	

}
